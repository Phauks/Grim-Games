/** A new random id. `randomBytes` fills an array with random bytes (crypto.getRandomValues). */
export function randomAccountId(
	randomBytes: (array: Uint8Array<ArrayBuffer>) => Uint8Array = (array) =>
		crypto.getRandomValues(array)
): string {
	const bytes = randomBytes(new Uint8Array(ACCOUNT_ID_WORDS));
	return Array.from(bytes, (byte) => ACCOUNT_ID_WORDLIST[byte]).join('-');
}

/** Whether `value` has the shape of a word-chain account id. */
export function isWordAccountId(value: string): boolean {
	const words = value.split('-');
	return words.length === ACCOUNT_ID_WORDS && words.every((word) => /^[a-z]{1,12}$/.test(word));
}

/** Accounts made before word-chain ids have a 64-character hex id (a Durable Object id). */
export function isLegacyAccountId(value: string): boolean {
	return /^[0-9a-f]{64}$/.test(value);
}
