/**
 * Writes docs/rules-parts.md: every part a character's rules block may have
 * (`src/lib/core/data/parts/index.ts`), with its label and description from the part itself,
 * its file, and the rules and engine files that read it. The catalogue replaces a hand-kept
 * list, so it can't drift from the parts (review H4, 2026-11-10).
 *
 * A reader is a file in `src/lib/core` or `src/lib/features` (tests and the parts aside) that
 * reads the part off a rules block: `rulesFor(...)?.key`, `rulesOf(...)?.key`, `rules?.key`,
 * `r.key` and the like. It is found by text, so it is a pointer, not a proof.
 *
 * Usage: `npm run parts:catalogue` (writes). `scripts/parts-catalogue.test.ts` fails if the
 * file on disk is stale.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
// The rules block's own module first: it loads the parts in the order their imports need.
import '../src/lib/core/data/character-rules.ts';
import * as PARTS from '../src/lib/core/data/parts/index.ts';

const root = new URL('../', import.meta.url);
const OUT = new URL('docs/rules-parts.md', root);
const READER_DIRS = ['src/lib/core', 'src/lib/features'];

function files(dir: string): string[] {
	const abs = fileURLToPath(new URL(dir, root));
	return readdirSync(abs).flatMap((name) => {
		const rel = `${dir}/${name}`;
		if (statSync(fileURLToPath(new URL(rel, root))).isDirectory()) return files(rel);
		if (rel.startsWith('src/lib/core/data/parts/') || name.includes('.test.')) return [];
		return name.endsWith('.ts') || name.endsWith('.svelte') ? [rel] : [];
	});
}

/** The part files by the key they export (`export { key } from './file.ts'`). */
function partFiles(): Map<string, string> {
	const index = readFileSync(new URL('src/lib/core/data/parts/index.ts', root), 'utf8');
	return new Map(
		[...index.matchAll(/export \{ (\w+) \} from '\.\/([\w-]+\.ts)';/g)].map((m) => [
			m[1],
			`src/lib/core/data/parts/${m[2]}`
		])
	);
}

export function catalogue(): string {
	const sources = READER_DIRS.flatMap(files).map((f) => ({
		file: f,
		text: readFileSync(new URL(f, root), 'utf8')
	}));
	const where = partFiles();
	const oneLine = (s: string) => s.replace(/\s+/g, ' ').trim();
	const rows = Object.entries(PARTS)
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([key, part]) => {
			const read = new RegExp(`(?:\\)|\\b(?:rules|r|block|own|rule|patch))\\??\\.${key}\\b`);
			const readers = sources
				.filter((s) => read.test(s.text))
				.map((s) => `\`${s.file.replace('src/lib/', '')}\``);
			return [
				`### ${key}`,
				'',
				`**${oneLine(part.label)}.** ${oneLine(part.description)}`,
				'',
				`- Part: \`${where.get(key) ?? 'src/lib/core/data/parts/'}\``,
				`- Read by: ${readers.length ? readers.join(', ') : 'none found by text'}`,
				''
			].join('\n');
		});
	return [
		'# Rules block parts',
		'',
		'<!-- Generated by scripts/generate-parts-catalogue.ts from src/lib/core/data/parts. Do not edit; run `npm run parts:catalogue`. -->',
		'',
		`Every key a character's rules block may have, ${rows.length} in all. Each is one file in`,
		'`src/lib/core/data/parts/`, with the label and description the Character builder shows.',
		'"Read by" lists the files that read the part off a rules block (found by text: a pointer).',
		'',
		...rows
	].join('\n');
}

if (process.argv.includes('--write')) writeFileSync(OUT, catalogue());
