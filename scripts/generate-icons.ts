/**
 * Writes one module per Phosphor weight to src/lib/ui/icons/generated/, each statically
 * importing every catalogue icon in that weight through unplugin-icons (`~icons/ph/...`).
 *
 * Why a generated module: unplugin-icons compiles icons at build time, so it only sees
 * static import ids; it cannot follow `~icons/${name}` built at runtime. The catalogue is
 * the single list of offered icons, and this script turns it into static imports. One
 * module per weight lets the app load only the weight a device uses.
 *
 * Usage: `npm run icons` (writes). `scripts/generate-icons.test.ts` fails if the files on
 * disk are stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { catalogueIconIds, PHOSPHOR_WEIGHTS, withWeight } from '../src/lib/ui/icons/catalogue.ts';

const outDir = new URL('../src/lib/ui/icons/generated/', import.meta.url);

export function generatedFiles(): Map<string, string> {
	const files = new Map<string, string>();
	for (const weight of PHOSPHOR_WEIGHTS) {
		const ids = catalogueIconIds().map((id) => withWeight(id, weight));
		const binding = (id: string) => id.replace(/[^a-z0-9]+/gi, '_');
		const lines = [
			'// Generated by scripts/generate-icons.ts from src/lib/ui/icons/catalogue.ts. Do not edit.',
			"import type { IconMap } from '../types.ts';",
			...ids.map((id) => `import ${binding(id)} from '~icons/${id.replace(':', '/')}';`),
			'',
			'const icons: IconMap = {',
			ids.map((id) => `\t'${id}': ${binding(id)}`).join(',\n'),
			'};',
			'',
			'export default icons;',
			''
		];
		files.set(`ph-${weight}.ts`, lines.join('\n'));
	}
	return files;
}

/** Fails loudly if a catalogue id is missing from the installed Iconify data. */
export function missingIcons(): string[] {
	const path = fileURLToPath(import.meta.resolve('@iconify-json/ph/icons.json'));
	const data = JSON.parse(readFileSync(path, 'utf8')) as {
		icons: Record<string, unknown>;
		aliases?: Record<string, unknown>;
	};
	const missing: string[] = [];
	for (const weight of PHOSPHOR_WEIGHTS) {
		for (const id of catalogueIconIds()) {
			const name = withWeight(id, weight).slice('ph:'.length);
			if (!data.icons[name] && !data.aliases?.[name]) missing.push(`ph:${name}`);
		}
	}
	return missing;
}

if (process.argv.includes('--write')) {
	const missing = missingIcons();
	if (missing.length) throw new Error(`Not in @iconify-json/ph: ${missing.join(', ')}`);
	for (const [name, content] of generatedFiles()) writeFileSync(new URL(name, outDir), content);
	console.log(`Wrote ${PHOSPHOR_WEIGHTS.length} icon modules to ${fileURLToPath(outDir)}`);
}
